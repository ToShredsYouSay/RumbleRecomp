"""Writes the generated achievement sets into tools/achievements from the facts in tools/collection_data.py:
collection.txt and shiny.txt (base game), collection_weekend.txt and shiny_weekend.txt (Weekend Edition), and
milestones.txt (defeat totals, every version).
  python tools/make_collection_sets.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import collection_data as cd

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'achievements')
PRIMARY = {int(k): cd.TYPES[int(v)] for k, v in (x.split(':') for x in cd.PRIMARY)}
AREA_ICON = {'Silent Forest': 'grass', 'Windy Prairie': 'flying', 'Rocky Cave': 'rock', 'Fiery Furnace': 'fire',
             'Bright Beach': 'water', 'Eternal Tower': 'ghost'}
AREA_ID = {'Silent Forest': 'forest', 'Windy Prairie': 'prairie', 'Rocky Cave': 'cave', 'Fiery Furnace': 'furnace',
           'Bright Beach': 'beach', 'Eternal Tower': 'tower'}
NOTE = ('# Generated by tools/make_collection_sets.py (do not edit by hand). Entries are named by dex number. "dex" and\n'
        '# "shiny" read the game\'s Collection screen (befriended is level 3). Which characters count, their main types,\n'
        '# and where they are found are in tools/collection_data.py.\n\n')


def runs(numbers):
    """[1,2,3,5] -> '1-3,5' (the list syntax of the dex condition)"""
    out, i, n = [], 0, sorted(set(numbers))
    while i < len(n):
        j = i
        while j + 1 < len(n) and n[j + 1] == n[j] + 1:
            j += 1
        out.append(str(n[i]) if i == j else f'{n[i]}-{n[j]}')
        i = j + 1
    return ','.join(out)


def save(name, title, versions, rows, default='off'):
    with open(os.path.join(OUT, name), 'w', encoding='utf8', newline='\n') as f:
        f.write(f'@title {title}\n@default {default}\n' + (f'@versions {versions}\n' if versions else '') + '\n' + NOTE)
        for r in rows:
            f.write('\t'.join(r) + '\n')
    print(name, len(rows), 'achievements')


def collection(name, title, versions, species, guests, generations, area_lists):
    rows = []
    total = len(species)
    for n in sorted(species + guests):
        kind = ', only given out by a ticket or password' if n in guests else ''
        rows.append((f'd{n:03d}', f'#{n:03d}', f'Befriend #{n:03d} ({PRIMARY[n].capitalize()} type{kind})',
                     f'dex {n}', f'type:{PRIMARY[n]}'))
    steps = [s for s in (10, 25, 50, 100, 150, 200, 300, 400) if s < total]
    for level, word, verb, icon in ((3, 'friends', 'Befriend', 'star'), (2, 'defeated', 'Defeat', 'flame'),
                                    (1, 'met', 'Meet', 'star')):
        for step in steps:
            title_s = f'{step} friends' if level == 3 else (f'{step} defeated' if level == 2 else f'{step} met')
            rows.append((f'{word}_{step}', title_s, f'{verb} {step} different characters' + (' (seen or better)' if level == 1 else ''),
                         f'dex {runs(species)} {level} {step}', icon))
    for t in cd.TYPES:
        group = [n for n in species if PRIMARY[n] == t]
        if group:
            rows.append((f'type_{t}', f'{t.capitalize()} collection', f'Befriend all {len(group)} {t.capitalize()}-type characters',
                         f'dex {runs(group)}', f'type:{t}'))
    for name_g, lo, hi in generations:
        group = [n for n in species if lo <= n <= hi]
        rows.append((f'gen_{name_g}', f'Generation {name_g} complete', f'Befriend all {len(group)} characters numbered #{lo:03d} to #{hi:03d}',
                     f'dex {runs(group)}', 'star'))
    for area, mode, label, members in area_lists:
        group = [n for n in members if n in species]
        if len(group) >= 2:
            rows.append((f'area_{AREA_ID[area]}_{mode}', f'{area} {label}', f'Befriend all {len(group)} characters found in {area} ({label})',
                         f'dex {runs(group)}', f'type:{AREA_ICON[area]}'))
    rows.append(('complete', 'Complete collection', f'Befriend all {total} characters in the stages', f'dex {runs(species)}', 'trophy'))
    save(name, title, versions, rows)


def shiny(name, title, versions, species, guests):
    everyone = sorted(species + guests)
    rows = []
    for n in everyone:
        rows.append((f's{n:03d}', f'#{n:03d} shiny', f'Befriend a shiny #{n:03d} ({PRIMARY[n].capitalize()} type)', f'shiny {n}', 'star'))
    for t in cd.TYPES:
        group = [n for n in everyone if PRIMARY[n] == t]
        if group:
            rows.append((f'shiny_type_{t}', f'Shiny {t.capitalize()}', f'Befriend a shiny {t.capitalize()}-type character (any of {len(group)})',
                         f'shiny {runs(group)}', f'type:{t}'))
    for step in (1, 5, 10, 25, 50, 100, 200, 400):
        if step < len(everyone):
            rows.append((f'shiny_{step}', 'A glint of luck' if step == 1 else f'{step} shiny friends',
                         'Befriend a shiny character' if step == 1 else f'Befriend {step} different shiny characters',
                         f'shiny {runs(everyone)} {step}', 'star'))
    rows.append(('shiny_complete', 'Shiny collection', f'Befriend a shiny of all {len(everyone)} characters',
                 f'shiny {runs(everyone)} {len(everyone)}', 'trophy'))
    save(name, title, versions, rows)


def milestones():
    rows = []
    for n in (100, 500, 1000, 2500, 5000, 10000, 25000, 50000, 100000):
        rows.append((f'defeats_{n}', f'{n} defeats', f'Defeat {n} characters in all', f'defeats 1-493 {n}', 'flame'))
    save('milestones.txt', 'Battle milestones', '', rows, default='on')


stage_v = [n for n in cd.VANILLA if n not in cd.VANILLA_GUESTS]
stage_w = [n for n in cd.WEEKEND if n not in cd.WEEKEND_GUESTS]


def area_lists(weekend):
    out = []
    for area in cd.AREAS:
        base = {m: cd.AREA_SPECIES.get((area, m), ([], []))[0] for m in ('normal', 'advanced')}
        gx = cd.AREA_SPECIES.get((area, 'gx'), ([], []))[1] if weekend else []
        out.append((area, 'all', 'residents', sorted(set(base['normal']) | set(base['advanced']) | set(gx))))
        out.append((area, 'normal', '(Normal)', base['normal']))
        out.append((area, 'another', '(Another)', base['advanced']))
        if gx:
            out.append((area, 'gx', 'GX', gx))
    return out


collection('collection.txt', 'Collection challenge', 'vanilla', stage_v, list(cd.VANILLA_GUESTS),
           [('1', 1, 151), ('4', 387, 493)], area_lists(False))
collection('collection_weekend.txt', 'Collection challenge (Weekend)', 'weekend weekend_patch1', stage_w, list(cd.WEEKEND_GUESTS),
           [('1', 1, 151), ('2', 152, 251), ('3', 252, 386), ('4', 387, 493)], area_lists(True))
shiny('shiny.txt', 'Shiny collection', 'vanilla', stage_v, list(cd.VANILLA_GUESTS))
shiny('shiny_weekend.txt', 'Shiny collection (Weekend)', 'weekend weekend_patch1', stage_w, list(cd.WEEKEND_GUESTS))
milestones()
